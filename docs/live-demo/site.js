function applyLanguage(lang) {
  const selected = translations[lang] ? lang : "en";
  document.documentElement.lang = selected === "zh" ? "zh-CN" : selected;
  localStorage.setItem("ctx-docs-lang", selected);

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const value = translations[selected][element.dataset.i18n];
    if (value) element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach(element => {
    const value = translations[selected][element.dataset.i18nAria];
    if (value) element.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-lang-option]").forEach(button => {
    const active = button.dataset.langOption === selected;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", active ? "true" : "false");
  });
}

function initLanguageSwitcher() {
  const initial = new URLSearchParams(window.location.search).get("lang")
    || localStorage.getItem("ctx-docs-lang")
    || "en";

  document.querySelectorAll("[data-lang-option]").forEach(button => {
    button.addEventListener("click", () => applyLanguage(button.dataset.langOption));
  });

  applyLanguage(initial);
}

document.addEventListener("DOMContentLoaded", initLanguageSwitcher);
